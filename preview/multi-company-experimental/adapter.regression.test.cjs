// Isolated multi-company adapter regression tests; mocked requests only, no Supabase writes.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const ctx={};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(__dirname+'/adapter.js','utf8'),ctx);
const api=ctx.StockPilotMultiCompany;
const A='11111111-1111-4111-8111-111111111111';
const B='22222222-2222-4222-8222-222222222222';
const invalid=['',null,undefined,'not-a-uuid','11111111-1111-4111-8111-11111111111g'];
for(const id of invalid)assert.throws(()=>api.validateCompanyId(id));
assert.equal(api.validateCompanyId(A),A);
for(const qty of [0,-1,1.5,1000001,NaN,Infinity,'1',null])assert.throws(()=>api.validateLines([{id:A,qty}]));
for(const lines of [[],new Array(101).fill({id:A,qty:1}),[{id:A,qty:1},{id:A.toUpperCase(),qty:2}]])assert.throws(()=>api.validateLines(lines));
assert.equal(api.validateLines([{id:A,qty:1}])[0].qty,1);
assert.equal(api.validateLines([{id:A,qty:1000000}])[0].qty,1000000);
(async()=>{
  let calls=[];
  const request=async (...args)=>{calls.push(args);return args[0].includes('companies')?[{id:A,name:'A'}]:'order-id';};
  const token=async()=> 'test-jwt';
  const companies=await api.listCompanies(request,token);
  assert.equal(companies.length,1);
  assert.equal(calls[0][1],'GET');
  assert.equal(calls[0][3],'test-jwt');
  assert.equal(calls[0][0],'/rest/v1/companies?select=id,name&order=name.asc');
  assert.equal(await api.createOrder(request,token,A,[{id:B,qty:2}]),'order-id');
  assert.equal(calls[1][0],'/rest/v1/rpc/stockpilot_v2_create_order_for_company');
  assert.equal(calls[1][1],'POST');
  assert.equal(calls[1][2].p_company_id,A);
  assert.equal(calls[1][2].p_lines[0].id,B);
  assert.equal(calls[1][3],'test-jwt');
  const n=calls.length;
  await assert.rejects(()=>api.createOrder(request,token,'bad',[{id:B,qty:1}]));
  await assert.rejects(()=>api.createOrder(request,token,A,[{id:B,qty:0}]));
  assert.equal(calls.length,n,'Invalid inputs must not send requests');
  await assert.rejects(()=>api.listCompanies(async()=>({error:'unexpected'}),token),/Liste entreprises invalide/);
  console.log('PASS: UUID, quantities, duplicates, token forwarding, REST paths, no request on invalid input');
})().catch(e=>{console.error(e);process.exitCode=1});
